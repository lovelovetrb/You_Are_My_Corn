import Head from "next/head";
import Link from "next/link";

import { useRouter } from "next/router";
import { useEffect, useState } from "react";

import { conditionsDataAtom, textAtom } from "@/lib/jotai";
import { useAtomValue } from "jotai";

import { MaxWidthLayout } from "@/components/MaxWidthLayout";
import Button from "@/components/button/Button";
import ButtonArea from "@/components/buttonArea/ButtonArea";
import TweetButton from "@/components/tweetButton/TweetButton";

import styles from "@/styles/Result.module.css";

import Loading from "@/components/Loading";
import NameForm from "@/components/nameForm/NameForm";
import Config from "@/lib/config";
import { ResultData } from "@/types/resultData";
import { SubmitData } from "@/types/submitData";

const Result = () => {
    const text = useAtomValue(textAtom);
    const data = useAtomValue(conditionsDataAtom);

    const [isLoaded, setIsLoaded] = useState(false);
    const [result, setResult] = useState<ResultData>({
        text: "",
        category: 0,
        score: 0,
        rank: 0,
        verificationHash: "",
    });

    const router = useRouter();
    useEffect(() => {
        const postData: SubmitData = {
            category: data.category,
            requiredWords: data.requiredWords,
            forbiddenWords: data.forbiddenWords,
            startTime: data.startTime,
            text,
            verificationHash: data.verificationHash,
        };
        const postDataToApi = async () => {
            await fetch(Config.apiUrl + "api/submit", {
                method: "POST",
                headers: {
                    "Content-Type": "application/json",
                },
                body: JSON.stringify(postData),
            }).then((res) => {
                if (res.ok) {
                    res.json().then((result) => {
                        setResult(result);
                        setIsLoaded(true);
                    });
                } else {
                    router.push("/500");
                }
            });
        };
        postDataToApi();
    }, []);

    return (
        <>
            <Head>
                <title>エモちゃれ!! - You Are My Corn</title>
                <meta name="description" content="Generated by create next app" />
                <meta name="viewport" content="width=device-width, initial-scale=1" />
                <link rel="icon" href="/favicon.ico" />
            </Head>
            <div className={styles.result}>
                {!isLoaded ? (
                    <Loading text="けっかをAIがけいさんちゅう" />
                ) : (
                    <>
                        <div className={styles.resultArea}>
                            <h2>Total score</h2>
                            <h2>{result.score}</h2>
                        </div>
                        <div>
                            {(() => {
                            if (data.score == 100) {
                                return <h2>{`称号: エモちゃれのを極めし者`}</h2>
                            }
                            else if(data.score >= 80){
                                return <h2>{`称号: エモちゃれのマスター!`}</h2>
                            } 
                            else if(data.score >= 50){
                                return <h2>{`称号: エモちゃれのベテラン`}</h2>
                            } 
                            else if(data.score >= 20){
                                return <h2>{`称号: のエモちゃれ駆け出し`}</h2>
                            } 
                            else {
                                return <h2>{`称号: 口下手...`}</h2>
                            } 
                            })()}
                        </div>
                        <div className={styles.inputNameArea}>
                            <h2>あなたはだい{result.rank}いだよ。なまえをかいて、ランクインしよう</h2>
                            <NameForm resultData={result} />
                        </div>
                        <div className={styles.buttonArea}>
                            <ButtonArea>
                                <TweetButton text="ツイート" result={result} />
                                <Link href="/">
                                    <Button text="HOME" />
                                </Link>
                            </ButtonArea>
                        </div>
                    </>
                )}
            </div>
        </>
    );
};

Result.getLayout = function getLayout(page: any) {
    return <MaxWidthLayout>{page}</MaxWidthLayout>;
};

export default Result;
