import Head from "next/head";
import Link from "next/link";

import { useState, useEffect } from "react";
import { useRouter } from "next/router";

import { useAtomValue } from "jotai";
import { playDataAtom, textAtom } from "@/lib/jotai";

import Button from "@/components/button/Button";
import TweetButton from "@/components/tweetButton/TweetButton";
import ButtonArea from "@/components/buttonArea/ButtonArea";
import { MaxWidthLayout } from "@/components/MaxWidthLayout";

import styles from "@/styles/Result.module.css";

import { submitData } from "@/types/submitData";
import { Result } from "@/types/result";
import NameForm from "@/components/nameForm/NameForm";

const Result = () => {
    const text = useAtomValue(textAtom);
    const data = useAtomValue(playDataAtom);

    // TODO: Load画面の作成
    const [isLoaded, setIsLoaded] = useState(false);
    const [result, setResult] = useState<Result>({
        text: "",
        category: 0,
        score: 0,
    });

    const router = useRouter();
    useEffect(() => {
        const postData: submitData = {
            category: data.category,
            requiredWords: data.requiredWords,
            forbiddenWords: data.forbiddenWords,
            startTime: data.startTime,
            text,
            verificationHash: data.verificationHash,
        };
        const postDataToApi = async () => {
            await fetch("http://localhost:3000/api/submit", {
                method: "POST",
                headers: {
                    "Content-Type": "application/json",
                },
                body: JSON.stringify(postData),
            }).then((res) => {
                if (res.ok) {
                    res.json().then((result) => {
                        setResult(result);
                        setIsLoaded(true);
                        console.log(result);
                    });
                } else {
                    router.push("/500");
                }
            });
        };
        postDataToApi();
    }, []);

    return (
        <>
            <Head>
                <title>Create Next App</title>
                <meta name="description" content="Generated by create next app" />
                <meta name="viewport" content="width=device-width, initial-scale=1" />
                <link rel="icon" href="/favicon.ico" />
            </Head>
            <div className={styles.result}>
                <div className={styles.resultArea}>
                    <h2>Total score</h2>
                    <h2>{result.score}</h2>
                </div>
                <div className={styles.inputNameArea}>
                    {/* TODO: ランク表示*/}
                    <h2>あなたはだい◯いだよ。なまえをかいて、らんくいんしよう</h2>
                    <NameForm />
                </div>
                <div className={styles.buttonArea}>
                    <ButtonArea>
                        <TweetButton text="ツイート" />
                        <Link href="/">
                            <Button text="HOME" />
                        </Link>
                    </ButtonArea>
                </div>
            </div>
        </>
    );
};

Result.getLayout = function getLayout(page: any) {
    return <MaxWidthLayout>{page}</MaxWidthLayout>;
};

export default Result;
